import type { Limitation, WorkoutPlace } from "./types";

/** Movement a session asks for; any exercise of the same slot can replace another. */
export type Slot = "squat" | "lunge" | "hinge" | "push" | "pull" | "core" | "cardio" | "arms" | "calves";

/** Groups of the catalog, in the order they are listed. */
export const SLOT_LABELS: Record<Slot, string> = {
  squat: "Pernas",
  lunge: "Avanço e degrau",
  hinge: "Glúteos e posterior",
  push: "Peito e ombros",
  pull: "Costas",
  arms: "Braços",
  calves: "Panturrilha",
  core: "Abdômen",
  cardio: "Cardio",
};

export interface Exercise {
  id: string;
  name: string;
  slot: Slot;
  places: WorkoutPlace[];
  /** Lowest level it suits: 1 iniciante, 2 intermediário, 3 avançado. */
  level: 1 | 2 | 3;
  /** Left out for people who reported pain there. */
  avoid: Limitation[];
  /** How the dose is given: repetitions, seconds of effort or continuous minutes. */
  unit: "reps" | "seconds" | "minutes";
  steps: string[];
  tip: string;
  /** Only added by hand from the catalog: the automatic plan never picks it. */
  catalogOnly?: true;
}

